export type TranslationKey = keyof typeof en;
export const tr = (locale: Locale, key: TranslationKey): string => (locale === "en" ? en : zh)[key] ?? en[key] ?? key;

export const I18nContext = createContext<Locale>("zh-CN");
export const useLocale = (): Locale => useContext(I18nContext);
export const useT = () => {
  const locale = useLocale();
  return (key: TranslationKey) => tr(locale, key);
};

